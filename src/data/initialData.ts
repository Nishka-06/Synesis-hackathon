export function generateSyntheticHistoricalArrivals(): HistoricalArrival[] {
  const records: HistoricalArrival[] = [];
  const now = new Date('2026-10-12T22:00:00Z');

  for (let i = 336; i >= 0; i--) {
    const timestamp = new Date(now.getTime() - i * 3600 * 1000);
    const hour = timestamp.getUTCHours();
    const day = timestamp.getUTCDay();
    const isWeekend = day === 0 || day === 6;

    // Diurnal curve: peaks in afternoon/evening (14:00 - 20:00), lowest at 04:00
    const diurnalFactor = Math.sin(((hour - 4) / 24) * 2 * Math.PI); // -1 to 1
    const baseHourFactor = Math.max(0.3, (diurnalFactor + 1) / 2); // 0.3 to 1.0

    // Weekend factor: higher ED trauma/injury, slightly lower elective surgery
    const weekendMultiplier = isWeekend ? 1.25 : 0.95;

    // ED arrivals
    const edBase = 6;
    const edNoise = (Math.sin(i * 1.7) * 1.5 + Math.cos(i * 2.3) * 1.2);
    const edCount = Math.max(1, Math.round(edBase * baseHourFactor * weekendMultiplier + edNoise));

    records.push({
      timestamp: timestamp.toISOString(),
      departmentId: 'ED',
      count: edCount,
      dayOfWeek: day,
      hourOfDay: hour,
      isWeekend,
    });

    // Med & Surg urgent admissions
    const medCount = Math.max(0, Math.round(edCount * 0.45));
    records.push({
      timestamp: timestamp.toISOString(),
      departmentId: 'MED',
      count: medCount,
      dayOfWeek: day,
      hourOfDay: hour,
      isWeekend,
    });
  }

  return records;
}

